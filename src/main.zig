	const Mem = struct {
		buff: []u8,
		interface: MosLib.boards.MMU.MemInterface,

		fn set_interface(self: *@This()) void {
			self.interface.mem_read = read;
			self.interface.mem_write = write;
		}

		fn read(interface: *MosLib.boards.MMU.MemInterface, addr: u24) u8 {
			const self: *@This() = @fieldParentPtr("interface", interface);
			if (addr > self.buff.len) {
				std.debug.print("Tried to read 0x{X:0>6} out of bounds\n", .{addr});
				return 0x00;
			}
			return self.buff[addr];
		}

		fn write(interface: *MosLib.boards.MMU.MemInterface, addr: u24, val: u8) void {
			const self: *@This() = @fieldParentPtr("interface", interface);
			if (addr > self.buff.len) {
				std.debug.print("Tried to write out of bounds\n", .{});
				return;
			}
			self.buff[addr] = val;
		}
